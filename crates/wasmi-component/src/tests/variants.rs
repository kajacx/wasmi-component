#[test]
fn test_huge_enum_dyn() {
    let cases = (0..260).map(|index| format!("case{index:03}"));
    let ty = ValueType::new_enum("massive260", cases);

    let value = &DynValue::new_enum("case258");
    assert_equal_repr_dyn(&ty, &value, &[2, 1]);
}

#[test]
fn test_variant_typed() {
    #[derive(Clone, Debug, PartialEq, ComponentValue)]
    enum Data {
        Number(f64),
        Text(String),
    }

    assert_equal_repr_typed(
        &Data::Number(42f64),
        &combine_slices([0u64.to_le_bytes(), 42f64.to_le_bytes()]),
    );

    assert_equal_repr_typed(
        &Data::Text("Hello".into()),
        &combine_slices([
            //determinant
            1u64.to_le_bytes().as_slice(),
            // start address and length
            16u32.to_le_bytes().as_slice(),
            5u32.to_le_bytes().as_slice(),
            // contents
            "Hello".as_bytes(),
        ]),
    );
}

fn combine_slices(slices: impl IntoIterator<Item = impl AsRef<[u8]>>) -> Vec<u8> {
    let mut result = Vec::new();
    for slice in slices {
        result.extend_from_slice(slice.as_ref());
    }
    result
}
